//! Backtest datasets: scenario schema + the seeded synthetic generator
//! (GAP-MAP P1 NEW).
//!
//! **Every scenario carries a [`DatasetLabel`].** The only variant that
//! exists is `Synthetic` — the generator is a seeded xorshift64 walk, and
//! the ≥50 golden fixtures under `tests/fixtures/backtest/` are its output,
//! checked in as JSON with `"label": "synthetic"` at the top level. A
//! future real-data pipeline must add a new variant (`Recorded`) and may
//! NOT reuse the synthetic one.

use serde::{Deserialize, Serialize};

/// Where a scenario's data came from. Surfaced in every report and every
/// fixture file; the UI must show it next to any number it renders.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum DatasetLabel {
    /// Generated by a seeded PRNG. Never real market data.
    Synthetic,
}

/// One market observation on the scenario's price path.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Tick {
    /// Milliseconds since scenario start.
    pub t_ms: u64,
    /// Spot price in SOL per whole token.
    pub price_sol: f64,
    /// SOL-side reserve available at this moment (lamports).
    pub quote_reserve_lamports: u64,
}

/// One self-contained backtest input.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BacktestScenario {
    /// ALWAYS present and always `synthetic` today (see module docs).
    pub label: DatasetLabel,
    /// Stable, order-independent id (fixture file names use this).
    pub name: String,
    /// Seed the generator used; informational for reproducibility.
    pub seed: u64,
    /// When the launch event reaches the sniper (ms since start).
    pub entry_t_ms: u64,
    /// Intended entry size (lamports of SOL).
    pub entry_quote_lamports: u64,
    /// Venue quote reserve at launch time, in SOL (drives the impact term).
    pub initial_reserve_sol: f64,
    /// Network congestion 0..=1 at entry (drives the landing threshold).
    pub congestion: f64,
    /// The price path. Sorted by `t_ms`, at least one tick.
    pub ticks: Vec<Tick>,
}

impl BacktestScenario {
    /// Validate the invariants the simulator relies on. Returns a list of
    /// defects (empty = usable); the simulator refuses invalid scenarios.
    pub fn defects(&self) -> Vec<String> {
        let mut out = Vec::new();
        if self.name.trim().is_empty() {
            out.push("name is empty".into());
        }
        if self.entry_quote_lamports == 0 {
            out.push("entry_quote_lamports is zero".into());
        }
        if !(self.initial_reserve_sol > 0.0) {
            out.push("initial_reserve_sol must be > 0".into());
        }
        if !(0.0..=1.0).contains(&self.congestion) {
            out.push(format!("congestion {} outside [0,1]", self.congestion));
        }
        if self.ticks.is_empty() {
            out.push("tick path is empty".into());
        }
        let mut last = None;
        for (i, t) in self.ticks.iter().enumerate() {
            if !(t.price_sol.is_finite() && t.price_sol > 0.0) {
                out.push(format!("tick[{i}] price {} not positive finite", t.price_sol));
            }
            if let Some(prev) = last {
                if t.t_ms <= prev {
                    out.push(format!("tick[{i}] time {} not increasing", t.t_ms));
                }
            }
            last = Some(t.t_ms);
        }
        out
    }
}

/// xorshift64 — the same family of PRNG the property suite uses; tiny,
/// deterministic, and never a source of cryptographic surprise here.
pub struct Xorshift64(pub u64);

impl Xorshift64 {
    pub fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }

    /// Uniform-ish value in [0, 1).
    pub fn unit(&mut self) -> f64 {
        (self.next_u64() >> 11) as f64 / ((1u64 << 53) as f64)
    }

    pub fn below(&mut self, n: u64) -> u64 {
        self.next_u64() % n
    }
}

/// The price paths offered to the generator: pump, dump, flat, chop.
const DRIFTS: [f64; 5] = [0.006, 0.001, 0.0, -0.001, -0.004];
const ENTRY_SIZES: [u64; 4] = [5_000_000, 10_000_000, 25_000_000, 50_000_000];
const CONGESTIONS: [f64; 4] = [0.0, 0.2, 0.5, 0.8];

/// Generate `count` deterministic scenarios from `seed`.
///
/// Scenario *i* uses drift `(seed + i) % 5`, entry size `(seed + i) % 4`,
/// congestion `(seed + i / 5) % 4` and its own xorshift stream seeded with
/// `seed * 1_000_003 + i`. Path: 200 ticks at 250 ms spacing (50 s),
/// ±2% random steps around the drift, reserves draining linearly from
/// `initial_reserve_sol` down to 90% of it.
pub fn synthetic_scenarios(seed: u64, count: usize) -> Vec<BacktestScenario> {
    let mut out = Vec::with_capacity(count);
    for i in 0..count {
        let idx = seed.wrapping_add(i as u64);
        let drift = DRIFTS[(idx % DRIFTS.len() as u64) as usize];
        let entry = ENTRY_SIZES[(idx % ENTRY_SIZES.len() as u64) as usize];
        let congestion = CONGESTIONS[((seed + (i / 5) as u64) % CONGESTIONS.len() as u64) as usize];
        let mut rng = Xorshift64(seed.wrapping_mul(1_000_003).wrapping_add(i as u64).max(1));

        let initial_reserve_sol = 30.0 + rng.unit() * 20.0; // 30..50 SOL
        let mut price = 0.000_000_03 + rng.unit() * 0.000_000_05;
        let mut ticks = Vec::with_capacity(200);
        for step in 0..200u64 {
            if step > 0 {
                // Consumed only when applied, exactly like the fixture
                // generator: the two implementations must stay bit-aligned.
                let shock = (rng.unit() * 2.0 - 1.0) * 0.02;
                price *= 1.0 + drift + shock;
                if price <= 0.0 {
                    price = 1e-9; // the walk floors instead of going non-positive
                }
            }
            let drain = 1.0 - 0.1 * (step as f64 / 199.0);
            ticks.push(Tick {
                t_ms: step * 250,
                price_sol: price,
                quote_reserve_lamports: (initial_reserve_sol * drain * 1e9) as u64,
            });
        }
        out.push(BacktestScenario {
            label: DatasetLabel::Synthetic,
            name: format!("syn_{seed:03}_{i:04}"),
            seed,
            entry_t_ms: 0,
            entry_quote_lamports: entry,
            initial_reserve_sol,
            congestion,
            ticks,
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generator_is_deterministic() {
        let a = synthetic_scenarios(9, 5);
        let b = synthetic_scenarios(9, 5);
        assert_eq!(a, b);
        let c = synthetic_scenarios(10, 5);
        assert_ne!(a, c);
    }

    #[test]
    fn generated_scenarios_are_well_formed_and_labelled() {
        for s in synthetic_scenarios(3, 20) {
            assert_eq!(s.label, DatasetLabel::Synthetic);
            assert!(s.defects().is_empty(), "{:?}: {:?}", s.name, s.defects());
            assert_eq!(s.ticks.len(), 200);
            assert!(s.ticks.iter().all(|t| t.price_sol > 0.0));
        }
    }

    #[test]
    fn defects_catch_broken_inputs() {
        let mut s = synthetic_scenarios(1, 1).pop().unwrap();
        s.entry_quote_lamports = 0;
        s.congestion = 1.5;
        s.ticks.clear();
        let d = s.defects();
        assert!(d.iter().any(|x| x.contains("entry_quote_lamports")));
        assert!(d.iter().any(|x| x.contains("congestion")));
        assert!(d.iter().any(|x| x.contains("empty")));
    }
}

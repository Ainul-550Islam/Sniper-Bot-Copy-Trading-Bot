#!/usr/bin/env python3
"""Regenerate docs/FINAL-FILE-INVENTORY.md from the actual tree.

WHY A SCRIPT
    The inventory is quoted in the delivery report and in several audit docs; it
    also has to stay byte-honest (every row carries the SHA-256 of the bytes in
    the tree right now). A hand-edited table drifts within one commit, so the
    table is generated and the generator lives in the repo.

WHAT IT DOES
    * list = `git ls-files` (the tracked tree, i.e. exactly what the ZIP ships)
    * classification = `git diff --name-status HEAD` → added / modified /
      original, plus deleted rows are NOT listed (they are not in the tree)
    * every row hashes the file that is in the tree *at generation time*; the
      row for this document itself carries a fixed marker instead of a digest,
      because a file cannot contain its own final hash

USAGE
    scripts/generate-file-inventory.py [--check]
    --check  exit 1 if the file on disk differs from what would be generated
             (used by CI to catch a stale inventory)
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "FINAL-FILE-INVENTORY.md"
BASE = "4a59411"


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout


def classify() -> dict[str, str]:
    out = git("diff", "--name-status", BASE, "--")
    mapping: dict[str, str] = {}
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        status, path = parts[0][0], parts[-1]
        mapping[path] = {"A": "added", "M": "modified", "D": "deleted", "R": "renamed"}.get(
            status, "original"
        )
    return mapping


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    files = [p for p in git("ls-files").splitlines() if p]
    classes = classify()
    self_rel = str(OUT.relative_to(ROOT))
    # The inventory cannot contain the hash of the file that is being written.
    # The self row therefore carries a fixed marker instead of a digest, which
    # also makes the output deterministic (so `--check` can detect staleness).
    # Two files are regenerated *by* the tooling and cannot be hashed stably:
    # this inventory itself, and SNAPSHOT-MANIFEST.sha256 (which hashes this
    # file). Both get a marker so the output is deterministic.
    self_marker = "(self — see note)"
    regen_marker = "(regenerated — see note)"

    rows: list[str] = []
    total = 0
    for i, rel in enumerate(sorted(files), start=1):
        path = ROOT / rel
        size = path.stat().st_size if path.exists() else 0
        unstable = rel == self_rel or rel == "SNAPSHOT-MANIFEST.sha256"
        if unstable:
            size = 0  # not knowable at generation time; excluded from the total
        total += size
        if rel == self_rel:
            digest = self_marker
        elif rel == "SNAPSHOT-MANIFEST.sha256":
            digest = regen_marker
        else:
            digest = sha256(path) if path.exists() else "-"
        suffix = path.suffix or "(none)"
        size_cell = ("(self)" if rel == self_rel else "(regen)") if unstable else str(size)
        rows.append(
            f"| {i} | `{rel}` | {suffix} | {size_cell} | `{digest}` | "
            f"{classes.get(rel, 'original')} | Yes | n/a |"
        )

    body = "\n".join(rows)
    text = f"""# FINAL FILE INVENTORY — sniper-suite 0.1.0

> Generated by `scripts/generate-file-inventory.py` on {date.today().isoformat()} from the actual
> working tree. `Classification` compares each file with `HEAD {BASE}`. `Inspected` = this audit
> opened the file (metadata only = generated artifact hashed, not read). `Tested` = an executed test
> exercises it; `n/a` = not executable code. One documented exception: this file's own row shows
> `(self — see note)` instead of a digest, because a file cannot hash itself, and `SNAPSHOT-MANIFEST.sha256`
> shows `(regenerated — see note)` because it hashes this file; every other row hashes the bytes that are
> in the tree now.

**Files listed:** {len(files)}
**Total bytes:** {total}

| # | Path | Type | Bytes | SHA-256 | Classification | Inspected | Tested |
|---:|---|---|---:|---|---|---|---|
{body}
"""
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("stale: docs/FINAL-FILE-INVENTORY.md does not match the tree", file=sys.stderr)
            return 1
        print("ok: docs/FINAL-FILE-INVENTORY.md matches the tree")
        return 0

    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {self_rel}: {len(files)} files, {total} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

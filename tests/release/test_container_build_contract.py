#!/usr/bin/env python3
"""Source-level container regression checks; not a substitute for an image build."""

import json
from pathlib import Path
import re
import shlex
import tomllib
import unittest

ROOT = Path(__file__).resolve().parents[2]


def builder_copies(text):
    """Read local COPY operands in the first build stage, without executing Docker."""
    sources = []
    stages = 0
    for raw in text.splitlines():
        line = raw.strip()
        if line.upper().startswith("FROM "):
            stages += 1
        if stages != 1 or not line.upper().startswith("COPY "):
            continue
        words = shlex.split(line)[1:]
        if words and not words[0].startswith("--"):
            sources.extend(words[:-1])
    return sources


class ContainerBuildContract(unittest.TestCase):
    def test_every_local_cargo_patch_is_copied_into_rust_builder(self):
        manifest = tomllib.loads((ROOT / "Cargo.toml").read_text())
        patches = manifest.get("patch", {}).get("crates-io", {})
        sources = builder_copies((ROOT / "Dockerfile").read_text())
        for name, patch in patches.items():
            if "path" not in patch:
                continue
            path = patch["path"].rstrip("/")
            with self.subTest(crate=name, path=path):
                self.assertTrue((ROOT / path / "Cargo.toml").is_file())
                self.assertTrue(
                    any(path == src.rstrip("/") or path.startswith(src.rstrip("/") + "/") for src in sources),
                    f"local Cargo patch {path} is missing from builder COPY inputs",
                )

    def test_rust_image_build_uses_the_committed_lockfile(self):
        text = (ROOT / "Dockerfile").read_text()
        build = next(line for line in text.splitlines() if line.startswith("RUN cargo build "))
        self.assertIn("--locked", shlex.split(build))

    def test_runtime_healthcheck_is_exec_form(self):
        text = (ROOT / "Dockerfile").read_text()
        match = re.search(r"HEALTHCHECK\b.*?\bCMD\s+([^\n]+)", text, re.DOTALL)
        self.assertIsNotNone(match)
        command = json.loads(match.group(1))
        self.assertEqual(command, ["curl", "-fsS", "http://127.0.0.1:8080/api/health"])

    def test_frontend_context_excludes_host_dependencies_and_secrets(self):
        path = ROOT / "apps/control-plane/.dockerignore"
        self.assertTrue(path.is_file(), "frontend context needs its own .dockerignore")
        rules = {line.strip() for line in path.read_text().splitlines() if line.strip() and not line.startswith("#")}
        for required in ["node_modules", ".next", "test-results", "playwright-report", ".env", ".env.*", "*.pem", "*.key"]:
            with self.subTest(rule=required):
                self.assertIn(required, rules)

    def test_tls_bind_sources_resolve_from_the_base_compose_directory(self):
        # Compose resolves relative bind paths against the FIRST file, not the
        # overlay directory. The documented invocation starts at repository root.
        text = (ROOT / "deploy/compose/docker-compose.tls.yml").read_text()
        sources = re.findall(r"(?m)^\s+-\s+(\.{1,2}/[^:\n]+):/etc/nginx/", text)
        self.assertEqual(len(sources), 3, "expected all three nginx file binds")
        for source in sources:
            with self.subTest(source=source):
                if Path(source).name == "dhparam.pem":
                    # Deliberately generated by bootstrap, not a shared key file
                    # committed to source. Check the producer and bind agree.
                    bootstrap = (ROOT / "scripts/bootstrap-tls.sh").read_text()
                    generated = re.search(r'(?m)^DHPARAM="([^"]+)"$', bootstrap)
                    self.assertIsNotNone(generated)
                    self.assertEqual((ROOT / source).resolve(), (ROOT / generated.group(1)).resolve())
                    self.assertIn('openssl dhparam -out "$DHPARAM" 4096', bootstrap)
                else:
                    self.assertTrue((ROOT / source).is_file(), f"missing TLS bind source: {source}")

    def test_frontend_runtime_uses_stable_numeric_identity(self):
        text = (ROOT / "apps/control-plane/Dockerfile").read_text()
        runtime = text[text.rfind("FROM "):]
        self.assertRegex(runtime, r"(?m)^USER 1000:1000$")


if __name__ == "__main__":
    unittest.main()
